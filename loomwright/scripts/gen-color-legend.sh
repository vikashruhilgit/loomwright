# css_name <#RRGGBB-uppercase> -> the camelCase-split CSS name, or the empty string.
css_name() {
  local hex="$1" line name
  line="$(css_table | grep -m1 -F -- "$hex " || true)"
  [ -n "$line" ] || return 0
  name="${line#* }"
  # camelCase -> spaced words: insert a space at every lower->UPPER boundary.
  printf '%s' "$name" | sed 's/\([a-z]\)\([A-Z]\)/\1 \2/g'
}

# ---------------------------------------------------------------------------
# Read agent frontmatter -> generated block on stdout.
# Only the FIRST frontmatter block of each file is read (awk `n==1`), so a
# `name:`/`color:` appearing in the prose body can never be mistaken for one.
# ---------------------------------------------------------------------------
frontmatter_field() {
  local file="$1" key="$2" val
  val="$(awk -v k="^$2:" '/^---$/{n++; next} n==1 && $0 ~ k {sub(/^[^:]*:[[:space:]]*/, ""); print; exit}' "$file")"
  # strip surrounding double quotes and trailing whitespace
  val="${val%\"}"; val="${val#\"}"
  printf '%s' "$val"
}

generate_block() {
  local f name color hex word rows=0
  printf '%s\n' "$BEGIN_MARK"
  printf '%s\n' '| Agent | Color | Hex |'
  printf '%s\n' '|-------|-------|-----|'
  for f in "$AGENTS_DIR"/*.md; do
    [ -f "$f" ] || continue
    name="$(frontmatter_field "$f" name)"
    color="$(frontmatter_field "$f" color)"
    [ -n "$name" ] || continue
    [ -n "$color" ] || continue
    name="${name#loomwright:}"
    hex="$(printf '%s' "$color" | tr '[:lower:]' '[:upper:]')"
    word="$(css_name "$hex")"
    [ -n "$word" ] || word='—'
    printf '| %s | %s | `%s` |\n' "$name" "$word" "$color"
    rows=$((rows + 1))
  done
  printf '%s\n' "$END_MARK"
  [ "$rows" -gt 0 ] || return 1
  return 0
}

# extract_block <doc> -> the marked block (inclusive of both markers) on stdout.
# Returns 1 when the marker pair is not present exactly once in the right order.
extract_block() {
  local doc="$1" b e
  [ -f "$doc" ] || return 1
  b="$(grep -c -F -- "$BEGIN_MARK" "$doc" || true)"
  e="$(grep -c -F -- "$END_MARK" "$doc" || true)"
  case "$b$e" in *[!0-9]*) return 1 ;; esac
  [ "$b" = "1" ] && [ "$e" = "1" ] || return 1
  awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
    index($0, b) { on=1 }
    on { print }
    index($0, e) { if (on) exit }
  ' "$doc"
}

GENERATED="$(generate_block)" || {
  echo "gen-color-legend: no agent frontmatter with both name: and color: found under $AGENTS_DIR — refusing to emit an empty legend" >&2
  exit 1
}

case "$MODE" in
  emit)
    printf '%s\n' "$GENERATED"
    exit 0
    ;;

  check)
    if [ ! -f "$DOC" ]; then
      echo "gen-color-legend: LEGEND MARKERS MISSING — document not found: $DOC" >&2
      exit 1
    fi
    current="$(extract_block "$DOC")" || {
      echo "gen-color-legend: LEGEND MARKERS MISSING — $DOC does not carry exactly one '$BEGIN_MARK' / '$END_MARK' pair. Add the marker pair around the Color Legend (Status Line) table, then run: bash loomwright/scripts/gen-color-legend.sh --write" >&2
      exit 1
    }
    if [ "$current" = "$GENERATED" ]; then
      echo "✓ color-legend: the generated legend matches agent frontmatter ($(printf '%s\n' "$GENERATED" | grep -c '^| .* | .* | `#') rows)."
      exit 0
    fi
    echo "gen-color-legend: LEGEND DRIFT — the Color Legend (Status Line) block in $DOC does not match agent frontmatter." >&2
    echo "  Regenerate with: bash loomwright/scripts/gen-color-legend.sh --write" >&2
    echo "  --- in $DOC" >&2
    echo "  +++ generated from $AGENTS_DIR" >&2
    diff <(printf '%s\n' "$current") <(printf '%s\n' "$GENERATED") 2>/dev/null | sed 's/^/  /' >&2
    exit 1
    ;;

  write)
    if [ ! -f "$DOC" ]; then
      echo "gen-color-legend: document not found: $DOC" >&2
      exit 1
    fi
    if ! extract_block "$DOC" >/dev/null; then
      echo "gen-color-legend: LEGEND MARKERS MISSING — $DOC does not carry exactly one '$BEGIN_MARK' / '$END_MARK' pair. Refusing to guess where the table goes; add the marker pair by hand first." >&2
      exit 1
    fi
    current="$(extract_block "$DOC")"
    if [ "$current" = "$GENERATED" ]; then
      echo "color-legend: no-op — $DOC already matches agent frontmatter."
      exit 0
    fi
    tmp="$DOC.gen-color-legend.tmp.$$"
    gen_file="$DOC.gen-color-legend.block.$$"
    printf '%s\n' "$GENERATED" > "$gen_file" || { echo "gen-color-legend: could not stage the generated block" >&2; exit 1; }
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" -v gf="$gen_file" '
      index($0, b) && !done { inblock=1; while ((getline line < gf) > 0) print line; close(gf); done=1; next }
      inblock { if (index($0, e)) { inblock=0 }; next }
      { print }
    ' "$DOC" > "$tmp" || { rm -f "$tmp" "$gen_file"; echo "gen-color-legend: rewrite failed; $DOC is unchanged" >&2; exit 1; }
    rm -f "$gen_file"
    mv "$tmp" "$DOC" || { rm -f "$tmp"; echo "gen-color-legend: could not replace $DOC" >&2; exit 1; }
    echo "color-legend: wrote $(printf '%s\n' "$GENERATED" | grep -c '^| .* | .* | `#') rows into $DOC."
    exit 0
    ;;
esac
