#!/usr/bin/env bash
# gen-color-legend.sh — generate the "Color Legend (Status Line)" table in
# loomwright/docs/ARCHITECTURE_CONTRACTS.md from agent frontmatter, and check it for drift.
#
# WHY: the legend was hand-maintained and drifted — on 2026-09-01 it carried 12 rows while 14
# agents declared a `color:`. Nothing mechanical noticed, because check-doc-currency.sh has no
# legend check. This script makes the table GENERATED OUTPUT with a `--check` mode wired into
# that gate, so the same drift cannot recur by hand.
#
# THE ONLY LOOKUP IS A PUBLISHED STANDARD.
#   Agent column = frontmatter `name:` minus the `loomwright:` prefix. Authoritative and exact —
#                  deliberately NOT a display-name map, which would have to be hand-edited on
#                  every agent added (the exact drift class this replaces).
#   Hex column   = frontmatter `color:` verbatim.
#   Color column = the CSS named-colour table below, keyed by HEX, camelCase-split.
#
#   Honest limit, stated rather than papered over: that CSS table IS a map embedded here. The
#   claim is not "no map anywhere" — it is that the only map is a PUBLISHED STANDARD keyed by
#   hex, so it cannot drift RELATIVE TO FRONTMATTER: change an agent's `color:` and the name
#   follows automatically. The table is the full standard list (147 entries + `RebeccaPurple`),
#   NOT a subset keyed to today's agent set: a subset would silently return the no-name fallback
#   for every colour a future agent picks. test-gen-color-legend.sh pins both branches — a hex
#   that is not a CSS name renders the em-dash fallback, and a CSS name from OUTSIDE the 14 in
#   use (`#FA8072` -> Salmon) must still resolve.
#
# SENTINELS: the table is written between
#   <!-- loomwright:color-legend BEGIN (generated by gen-color-legend.sh) -->
#   <!-- loomwright:color-legend END -->
# so a re-stamp keys off the marker rather than off a heading, and is idempotent. `--write`
# REFUSES a document with no marker pair rather than guessing where the table goes.
#
# MODES
#   (no args)   emit the generated block to stdout. Writes nothing.
#   --write     replace the marked block in the doc, in place. Idempotent (byte-compare first).
#   --check     compare the doc's marked block against the generated one. Exit 1 + a specific
#               diagnostic (`LEGEND DRIFT` / `LEGEND MARKERS MISSING`) on any mismatch.
#
# Overrides (self-test fixtures only; unset in real runs):
#   --agents-dir <dir>   directory of agent *.md files
#   --doc <path>         the document carrying the marked block
#
# EXIT CODES: 0 = clean / emitted. 1 = drift, missing markers, or an error (unreadable agents
# dir, no agents found, unreadable doc). This is a CORRECTNESS GATE, not a runtime emitter —
# it fails CLOSED and carries no `|| true` (CLAUDE.md §"Failure-Mode Invariants").
#
# Portability: bash 3.2 / BSD userland safe. No associative arrays, no GNU-only sed/date/stat
# flags, no `${var//…}` pattern substitution. LC_ALL=C pins glob collation so row order is
# identical on macOS and on Linux CI.

set -uo pipefail
export LC_ALL=C

script_dir="$(cd "$(dirname "$0")" && pwd)"
repo_root="$(cd "$script_dir/../.." && pwd)"

AGENTS_DIR="$repo_root/loomwright/agents"
DOC="$repo_root/loomwright/docs/ARCHITECTURE_CONTRACTS.md"
MODE="emit"

BEGIN_MARK='<!-- loomwright:color-legend BEGIN (generated by gen-color-legend.sh) -->'
END_MARK='<!-- loomwright:color-legend END -->'

while [ $# -gt 0 ]; do
  case "$1" in
    --write)       MODE="write" ;;
    --check)       MODE="check" ;;
    --agents-dir)  shift; AGENTS_DIR="${1:-}" ;;
    --doc)         shift; DOC="${1:-}" ;;
    *) echo "gen-color-legend: unknown argument '$1' (expected --write | --check | --agents-dir <dir> | --doc <path>)" >&2; exit 1 ;;
  esac
  shift
done

[ -d "$AGENTS_DIR" ] || { echo "gen-color-legend: agents directory not found: $AGENTS_DIR" >&2; exit 1; }

