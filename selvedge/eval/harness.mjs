const f4 = (v) => (v === null || v === undefined ? 'n/a' : v.toFixed(4));
const ci = (r) => (r.ci95.lower === null ? 'n/a' : `${f4(r.ci95.lower)} – ${f4(r.ci95.upper)}`);

function latest(reports, set) {
  for (let i = reports.length - 1; i >= 0; i--) if (reports[i].set === set) return reports[i];
  return null;
}

function reportLines(r) {
  const head = `**${r.set === 'held-out' ? 'Held-out' : 'Tuning'} set — selvedge ${r.engine.selvedge_version}, planner ${r.engine.planner_model}, ${String(r.ts).slice(0, 10)}, ${r.cases} case(s).**`;
  const gate = r.gate ? `Phase 3 gate: **${r.gate.verdict}**${r.gate.failed.length ? ` (${r.gate.failed.join('; ')})` : ''}.` : 'Phase 3 gate: not evaluated (the gate reads held-out reports only).';
  const rows = [
    ['false-PASS (PASS on known-FAIL)', r.rates.false_pass],
    ['false-FAIL (FAIL on known-PASS)', r.rates.false_fail],
    ['abstention (BLOCKED + NOT_VERIFIABLE)', r.rates.abstention],
  ].map(([label, x]) => `| ${label} | ${x.numerator} / ${x.denominator} | ${f4(x.rate)} | ${ci(x)} |`);
  const rr = r.repeatability;
  return [
    head,
    '',
    gate,
    '',
    '| Rate | Numerator / denominator | Point estimate | 95% interval (Clopper-Pearson) |',
    '|---|---|---|---|',
    ...rows,
    '',
    `model-judged criteria, counted apart: ${r.model_judged.criteria}. Runner flips: ${rr.runner.flipped} of ${rr.runner.cases} case(s) over ${rr.runner.repeats} run(s) of one frozen plan; planner flips: ${rr.planner.flipped} of ${rr.planner.cases} case(s) over ${rr.planner.repeats} fresh plan(s).`,
  ];
}

// renderBlock(results) → the README block, markers included.
export function renderBlock(results) {
  const lines = [BLOCK_BEGIN, '', `Generated from [\`eval/results.json\`](eval/results.json), which holds every report; the latest of each set is shown. Gate: false-PASS point estimate at most ${GATE.false_pass_max} and abstention at most ${GATE.abstention_max} on a held-out set with a known-FAIL denominator at or above its floor.`, ''];
  const shown = SETS.map((s) => latest(results.reports, s)).filter(Boolean);
  if (shown.length === 0) lines.push('No report yet.', '');
  for (const r of shown) lines.push(...reportLines(r), '');
  lines.push(BLOCK_END);
  return lines.join('\n');
}

function readmeBlock(text) {
  const b = text.indexOf(BLOCK_BEGIN);
  const e = text.indexOf(BLOCK_END);
  if (b === -1 && e === -1) return null;
  if (b === -1 || e === -1 || e < b) return { broken: true };
  return { start: b, end: e + BLOCK_END.length, body: text.slice(b, e + BLOCK_END.length) };
}

function cmdReadme(opts) {
  const results = readResults(opts.results, { mayBeAbsent: false });
  const text = readFileSync(opts.readme, 'utf8');
  const block = renderBlock(results);
  const cur = readmeBlock(text);
  let next;
  if (cur && cur.broken) throw markersMissing(`${opts.readme} has one results marker without the other`);
  if (cur) next = text.slice(0, cur.start) + block + text.slice(cur.end);
  else {
    const at = text.indexOf(`\n${README_SECTION}\n`);
    if (at === -1) throw markersMissing(`${opts.readme} has no results markers and no "${README_SECTION}" heading to put them under`);
    const nextHeading = text.indexOf('\n## ', at + 1 + README_SECTION.length);
    const cut = nextHeading === -1 ? text.length : nextHeading + 1;
    next = `${text.slice(0, cut).replace(/\n*$/, '\n\n')}${block}\n\n${text.slice(cut)}`;
  }
  if (next !== text) writeAtomic(opts.readme, next);
  say(`harness: OK — ${opts.readme} results block written from ${opts.results}`);
  return 0;
}

function cmdCheckReadme(opts) {
  const text = readFileSync(opts.readme, 'utf8');
  const cur = readmeBlock(text);
  if (!existsSync(opts.results)) {
    if (cur) throw outOfSync(`${opts.readme} carries a results block but ${opts.results} does not exist`);
    say(`harness: OK — no results file and no results block in ${opts.readme}`);
    return 0;
  }
  const want = renderBlock(readResults(opts.results, { mayBeAbsent: false }));
  if (!cur || cur.broken || cur.body !== want) throw outOfSync(`the results block in ${opts.readme} is not what \`node selvedge/eval/harness.mjs readme\` writes from ${opts.results}; run it`);
  say(`harness: OK — the results block in ${opts.readme} matches ${opts.results}`);
  return 0;
}

