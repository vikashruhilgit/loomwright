// The set check; throws (writing nothing) on any problem. Returns the cases with their known answers.
function checkedCases(repo, set, outside) {
  const argv = [set === 'held-out' ? 'count' : 'validate', '--repo', repo];
  const code = evalSetMain(argv);
  if (code !== 0) throw new Failure([]);
  const ctx = { problems: [], leaks: new Set(), invalid: [], answerGaps: [] };
  const s = loadSet(repo, ctx);
  const raw = set === 'held-out' ? s.heldOut : s.tuning;
  const answers = set === 'held-out' ? readAnswers(s.heldOut, ctx, outside) : null;
  const entries = s.realBugs.entries.filter((e) => isObj(e) && e.status === 'used');
  return raw.map((c) => ({
    case_id: c.case_id,
    group_id: c.group_id,
    criterion: c.criterion,
    target: c.target,
    app: c.target.kind === 'commit' ? c.target.repo : 'sample-app',
    known: set === 'held-out' ? answers[c.case_id] : c.answer,
    setup: setupFor(c.target, entries),
  }));
}

// The setup lines real-bugs.json recorded for a commit (its role in every entry that names it).
function setupFor(target, entries) {
  if (target.kind !== 'commit') return [];
  const out = [];
  for (const e of entries) {
    if (e.repo !== target.repo) continue;
    for (const [role, sha] of [['parent', e.parent_sha], ['fix', e.fix_sha]]) {
      if (sha !== target.sha) continue;
      const lines = Array.isArray(e.setup) ? e.setup : e.setup[role];
      for (const l of lines) if (!out.includes(l)) out.push(l);
    }
  }
  return out;
}

function targetKey(t) {
  return t.kind === 'commit' ? `${t.repo}@${t.sha}` : `variant:${t.path}`;
}

function groupTargets(cases, set, repo, outside) {
  const byKey = new Map();
  for (const c of cases) {
    const k = targetKey(c.target);
    if (!byKey.has(k)) {
      const t = { ...c.target, setup: c.setup };
      if (t.kind === 'variant') t.dir = set === 'held-out' ? join(outside, t.path) : join(repo, EVAL_REL, 'tuning', t.path);
      byKey.set(k, { key: k, target: t, cases: [] });
    }
    byKey.get(k).cases.push(c);
  }
  return [...byKey.values()].map((g, i) => ({ ...g, slug: `${String(i + 1).padStart(3, '0')}-${createHash('sha256').update(g.key).digest('hex').slice(0, 10)}` }));
}

