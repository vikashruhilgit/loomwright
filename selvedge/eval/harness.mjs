// harness.mjs — runs the normal Selvedge path (plan → freeze → model-free run → verdict) on every
// known-answer case of one side of the set, scores the verdicts against the known answers, appends
// a per-engine-version report to selvedge/eval/results.json, prints the rates and the Phase 3 gate
// line, and keeps the generated results block in selvedge/README.md equal to that file. An
// owner-only measurement tool, like eval-set.mjs; the arithmetic is stats.mjs's.
//
//   node selvedge/eval/harness.mjs run --set held-out|tuning [--planner-repeats N] [--runner-repeats N]
//                                      [--work-dir <dir> [--resume]] [--results <file>]
//   node selvedge/eval/harness.mjs score --work-dir <dir> [--results <file>]
//                                      score a finished work dir again, append its report
//   node selvedge/eval/harness.mjs readme [--results <file>] [--readme <file>]
//                                      rewrite the README results block from the results file
//   node selvedge/eval/harness.mjs check-readme [--results <file>] [--readme <file>]
//                                      fail when the block differs from what `readme` would write
//
// Every command takes --repo <dir> (the repository top level; default: the checkout this file is
// in). The set is checked first (eval-set.mjs `count` for held-out: validate, the manifest check and
// the answers check; `validate` for tuning) and any problem stops the run before a target is brought
// up or a file is written; those lines are eval-set.mjs's own (`eval-set: FAIL <token>: …`).
//
// A target (one commit, or one planted variant) is brought up once for all its cases by the target
// driver (target-driver.sh, or the command in SELVEDGE_EVAL_TARGET_DRIVER): `up <target.json> <dir>`
// prints `origin=<url>` and `root=<dir>`, `down <dir>` takes it down, `stop <dir>` (once, at the end)
// stops what it shares between targets. Each target gets its own workspace (a git repo under the
// work dir, outside this repository) holding criteria.json and a selvedge.json that allows only the
// driver's origin. The selvedge CLI is selvedge/bin/selvedge (SELVEDGE_EVAL_SELVEDGE_BIN overrides
// it). SELVEDGE_PLANNER_TOKEN_BUDGET is removed from the environment of every selvedge child.
//
// Reason tokens, printed `harness: FAIL <token>: <detail>` on stderr. Each token sits on exactly one
// code line, the line that records that failure, so a test can pin it:
//   target_unavailable, results_invalid, readme_results_out_of_sync, readme_markers_missing,
//   work_dir_invalid, run_incomplete
//
// Exit codes: 0 ok (a report was written, whatever the gate says), 1 a named failure, 2 usage error
// or cannot run. Node >= 18, standard library only.
