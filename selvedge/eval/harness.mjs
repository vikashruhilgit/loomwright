function driverCmd(env = process.env) {
  return (env.SELVEDGE_EVAL_TARGET_DRIVER || '').trim() || `bash ${JSON.stringify(join(HERE, 'target-driver.sh'))}`;
}

function runDriver(sub, args, logBase) {
  const r = spawnSync('/bin/sh', ['-c', `${driverCmd()} "$@"`, 'sh', sub, ...args], { encoding: 'utf8', env: process.env, maxBuffer: 64 * 1024 * 1024 });
  writeFileSync(`${logBase}.out`, r.stdout || '');
  writeFileSync(`${logBase}.err`, `${r.stderr || ''}${r.error ? `\n${r.error.message}` : ''}`);
  return r;
}

function selvedgeBin() {
  return (process.env.SELVEDGE_EVAL_SELVEDGE_BIN || '').trim() || join(PLUGIN_DIR, 'bin', 'selvedge');
}

// One selvedge child, async (plans run side by side). Resolves {code, stdout, stderr}.
function selvedgeAsync(args, cwd, logBase) {
  return new Promise((done) => {
    const child = spawn(selvedgeBin(), args, { cwd, env: childEnv(), stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (d) => (stdout += d));
    child.stderr.on('data', (d) => (stderr += d));
    child.on('error', (e) => (stderr += `\n${e.message}`));
    child.on('close', (code) => {
      writeFileSync(`${logBase}.out`, stdout);
      writeFileSync(`${logBase}.err`, stderr);
      done({ code, stdout, stderr });
    });
  });
}

function selvedgeSync(args, cwd, logBase) {
  const r = spawnSync(selvedgeBin(), args, { cwd, env: childEnv(), encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024 });
  writeFileSync(`${logBase}.out`, r.stdout || '');
  writeFileSync(`${logBase}.err`, `${r.stderr || ''}${r.error ? `\n${r.error.message}` : ''}`);
  return { code: r.status, stdout: r.stdout || '', stderr: r.stderr || '' };
}

function runsLog(ws) {
  const file = join(ws, '.selvedge', 'runs.jsonl');
  if (!existsSync(file)) return [];
  return readFileSync(file, 'utf8').split('\n').filter(Boolean).map((l) => {
    try {
      return JSON.parse(l);
    } catch {
      return {};
    }
  });
}

const tokensOf = (t) => (isObj(t) ? (t.input_tokens || 0) + (t.output_tokens || 0) : 0);

// Every criterion of a target with one verdict, e.g. a plan that never froze.
function allAs(criteria, verdict, reason) {
  return Object.fromEntries(criteria.map((c) => [c.id, { verdict, evidence_class: null, reason }]));
}

function verdictsFrom(file, criteria, reasonIfMissing) {
  if (!file || !existsSync(file)) return allAs(criteria, 'BLOCKED', reasonIfMissing);
  const v = readJsonFile(file);
  return Object.fromEntries(criteria.map((c) => {
    const x = isObj(v.criteria) ? v.criteria[c.id] : null;
    return [c.id, x ? { verdict: x.verdict, evidence_class: x.evidence_class, reason: x.reason || null } : { verdict: 'BLOCKED', evidence_class: null, reason: 'run_interrupted' }];
  }));
}

// The runs[] entry of a plan that did not freeze: nothing ran, its planner tokens are not known.
const notRun = (target, plan) => ({ target, plan, run: null, run_id: null, planner_tokens: null, duration_ms: null });

// `selvedge run` (or `run --replay`): its verdicts, run id and duration.
function runOnce(args, ws, logBase, criteria) {
  const r = selvedgeSync(args, ws, logBase);
  const m = /^verdict \S+ (.+verdict\.json)$/m.exec(r.stdout);
  const file = m ? m[1].trim() : null;
  const reason = (/^BLOCKED (\S+)/m.exec(r.stdout) || [])[1] || `run_exit_${r.code}`;
  const runId = file ? basename(dirname(file)) : null;
  const line = runId ? runsLog(ws).find((l) => l.event === 'run' && l.run_id === runId) : null;
  return { verdicts: verdictsFrom(file, criteria, reason), runId, runDir: file ? dirname(file) : null, duration_ms: line ? line.duration_ms : null };
}

async function runTarget(g, tdir, opts) {
  const criteria = [];
  for (const c of g.cases) if (!criteria.some((x) => x.id === c.criterion.id)) criteria.push({ id: c.criterion.id, text: c.criterion.text });
  mkdirSync(join(tdir, 'logs'), { recursive: true });
  writeFileSync(join(tdir, 'target.json'), jsonText(g.target));
  const up = runDriver('up', [join(tdir, 'target.json'), join(tdir, 'driver')], join(tdir, 'logs', 'driver-up'));
  const origin = up.status === 0 ? (/^origin=(\S+)$/m.exec(up.stdout || '') || [])[1] : undefined;
  if (!origin) {
    runDriver('down', [join(tdir, 'driver')], join(tdir, 'logs', 'driver-down'));
    const tail = `${up.stderr || ''}${up.error ? up.error.message : ''}`.trim().split('\n').slice(-3).join(' | ');
    throw new Failure([`target_unavailable: ${g.key} — the target driver's up exited ${up.status}${tail ? `: ${tail}` : ' and printed no origin='} (logs: ${join(tdir, 'logs')})`]);
  }
  try {
    const ws = join(tdir, 'ws');
    mkdirSync(ws, { recursive: true });
    if (!existsSync(join(ws, '.git'))) execFileSync('git', ['init', '-q', ws], { stdio: 'ignore' });
    writeFileSync(join(ws, '.gitignore'), '.selvedge/\n');
    writeFileSync(join(ws, 'selvedge.json'), jsonText({ schema_version: 1, origins: [origin], allow_remote: false, allow_remote_mutation: false }));
    writeFileSync(join(ws, 'criteria.json'), jsonText({ schema_version: 1, source: null, criteria }));
    note(`${g.key}: up at ${origin}; ${opts.plannerRepeats} plan(s) of ${criteria.length} criterion(s)`);
    const planned = await Promise.all(Array.from({ length: opts.plannerRepeats }, (_, i) => selvedgeAsync(['plan', 'criteria.json'], ws, join(tdir, 'logs', `plan-${i + 1}`))));
    const plans = [];
    const frozenPlans = [];
    const replays = [];
    const runs = [];
    const freezes = runsLog(ws).filter((l) => l.event === 'freeze');
    for (let p = 0; p < planned.length; p++) {
      const pr = planned[p];
      const dir = pr.stdout.trim().split('\n').filter(Boolean).pop();
      const frozen = Boolean(pr.code === 0 && dir && existsSync(join(dir, 'plan.sha256')));
      frozenPlans.push(frozen);
      if (!frozen) {
        // The plan's verdicts are BLOCKED with the planner's reason (they count as abstention), but
        // nothing ran: no replays of it, and a runs[] entry that says so (no run, tokens unknown).
        const reason = PLAN_REASONS.find((t) => pr.stderr.includes(t)) || `plan_exit_${pr.code}`;
        plans.push(allAs(criteria, 'BLOCKED', reason));
        runs.push(notRun(g.key, p + 1));
        continue;
      }
      const fl = freezes.find((l) => l.run_id === basename(dir));
      const ptok = fl ? tokensOf(fl.planner_tokens) : 0;
      const first = runOnce(['run', '--non-interactive', dir], ws, join(tdir, 'logs', `run-${p + 1}-1`), criteria);
      plans.push(first.verdicts);
      runs.push({ target: g.key, plan: p + 1, run: 1, run_id: first.runId, planner_tokens: ptok, duration_ms: first.duration_ms });
      if (p !== 0) continue;
      for (let r = 1; r < opts.runnerRepeats; r++) {
        const rep = runOnce(['run', '--replay', dir, '--non-interactive'], ws, join(tdir, 'logs', `run-1-${r + 1}`), criteria);
        replays.push(rep.verdicts);
        runs.push({ target: g.key, plan: 1, run: r + 1, run_id: rep.runId, planner_tokens: 0, duration_ms: rep.duration_ms });
      }
    }
    return { key: g.key, status: 'done', origin, plans, frozen: frozenPlans, replays, runs };
  } finally {
    runDriver('down', [join(tdir, 'driver')], join(tdir, 'logs', 'driver-down'));
  }
}

