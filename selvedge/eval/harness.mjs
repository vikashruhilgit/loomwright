// --- results file ------------------------------------------------------------------------------

function readResults(file, { mayBeAbsent }) {
  if (!existsSync(file)) {
    if (mayBeAbsent) return { schema_version: 1, reports: [] };
    throw resultsInvalid(`${file} does not exist; run the harness first`);
  }
  let v;
  try {
    v = readJsonFile(file);
  } catch (e) {
    v = e;
  }
  if (!(isObj(v) && v.schema_version === 1 && Array.isArray(v.reports) && v.reports.every((r) => isObj(r) && SETS.includes(r.set) && isObj(r.rates) && isObj(r.engine)))) {
    throw resultsInvalid(`${file} is not {"schema_version": 1, "reports": [...]} with a set, engine and rates on every report`);
  }
  return v;
}

