function insideRepo(repo, dir) {
  const rel = relative(realpathOrResolve(repo), realpathOrResolve(dir));
  return rel === '' || !(rel.startsWith('..') || rel.startsWith(sep) || /^[A-Za-z]:/.test(rel));
}

function caseIdsHash(cases) {
  return createHash('sha256').update(cases.map((c) => c.case_id).sort().join('\n')).digest('hex');
}

// A finished target's result with `frozen` (one flag per plan) and only runs that happened. A
// result written before `frozen` existed carries made-up BLOCKED replays and a runs[] entry for a
// plan that never froze; plan p froze iff its first run left logs/run-<p>-1.out (runOnce is the only
// writer, and it runs a frozen plan only), so the flags are read back from the target's logs.
function normalized(res, tdir) {
  const frozen = Array.isArray(res.frozen) ? res.frozen : res.plans.map((_, p) => existsSync(join(tdir, 'logs', `run-${p + 1}-1.out`)));
  const runs = res.runs.map((r) => (r.run === 1 && frozen[r.plan - 1] === false ? notRun(r.target, r.plan) : r));
  return { ...res, frozen, runs, replays: frozen[0] ? res.replays : [] };
}

function report(meta, cases, groups, workDir) {
  const tdirs = groups.map((g) => join(workDir, 'targets', g.slug));
  const results = tdirs.map((t) => {
    const f = join(t, 'result.json');
    return existsSync(f) ? readJsonFile(f) : null;
  });
  const missing = groups.filter((g, i) => !(results[i] && results[i].status === 'done'));
  if (missing.length) throw new Failure([`run_incomplete: ${missing.length} of ${groups.length} target(s) have no finished result in ${workDir} (first: ${missing[0].key}); finish them with run --work-dir ${workDir} --resume`]);
  for (let i = 0; i < results.length; i++) results[i] = normalized(results[i], tdirs[i]);
  // Only targets whose plan 1 froze were replayed; their cases alone make the runner series.
  const replayed = groups.map((g, i) => results[i].frozen[0]);
  const perCase = (series) => {
    const out = {};
    for (let i = 0; i < groups.length; i++) {
      if (series.kind === 'replays' && !replayed[i]) continue;
      for (const c of groups[i].cases) out[c.case_id] = results[i][series.kind][series.index][c.criterion.id];
    }
    return out;
  };
  const plans = Array.from({ length: meta.planner_repeats }, (_, i) => perCase({ kind: 'plans', index: i }));
  const replays = Array.from({ length: meta.runner_repeats - 1 }, (_, i) => perCase({ kind: 'replays', index: i }));
  const notReplayed = groups.flatMap((g, i) => (replayed[i] ? [] : g.cases.map((c) => c.case_id)));
  return buildReport({
    set: meta.set,
    engine: meta.engine,
    ts: new Date().toISOString(),
    cases: cases.map((c) => ({ case_id: c.case_id, group_id: c.group_id, app: c.app, known: c.known })),
    plans,
    replays,
    not_replayed: notReplayed,
    runs: results.flatMap((r) => r.runs),
  });
}

function printReport(r) {
  const row = (label, x) => `${label.padEnd(12)} ${String(x.numerator).padStart(4)} / ${String(x.denominator).padEnd(4)}  ${f4(x.rate)}   95% CI ${ci(x)}`;
  say(`report: set ${r.set}, selvedge ${r.engine.selvedge_version}, planner ${r.engine.planner_model}, ${r.cases} case(s)`);
  say(row('false-PASS', r.rates.false_pass));
  say(row('false-FAIL', r.rates.false_fail));
  say(row('abstention', r.rates.abstention));
  say(`verdicts: ${Object.entries(r.verdict_counts).map(([k, v]) => `${k} ${v}`).join(', ')}`);
  for (const [k, v] of Object.entries(r.abstention_reasons)) say(`  abstained: ${k} × ${v}`);
  say(`budget_exceeded BLOCKED (counted in abstention, shown on its own): ${r.budget_exceeded}`);
  say(`model-judged (kept apart): ${r.model_judged.criteria} criterion(s)`);
  for (const kind of ['runner', 'planner']) {
    const x = r.repeatability[kind];
    say(`${kind} flips: ${x.flipped} of ${x.cases} case(s) over ${x.repeats} ${kind === 'runner' ? 'run(s) of plan 1' : 'plan(s)'}${x.flipped ? `: ${x.flips.map((f) => `${f.case_id} ${f.verdicts.join('/')}`).join(', ')}` : ''}`);
  }
  say(`planner tokens ${r.totals.planner_tokens}, run time ${r.totals.duration_ms} ms over ${r.runs.length} run(s)`);
  say(r.gate ? `gate: ${r.gate.verdict}${r.gate.failed.length ? ` — ${r.gate.failed.join('; ')}` : ''}` : `gate: not evaluated (set ${r.set}; the gate reads held-out reports only)`);
}

function appendAndPrint(opts, rep) {
  const results = readResults(opts.results, { mayBeAbsent: true });
  results.reports.push(rep);
  writeAtomic(opts.results, jsonText(results));
  printReport(rep);
  const rule = revisionRule(results.reports);
  if (rule.stop) say(`two-revision rule: the held-out reports of selvedge ${rule.versions.join(' and ')} each miss the gate on a full known-FAIL denominator — stop and run the section 8 review now. The gate and the abstention cap stay as they are.`);
  say(`harness: OK — report appended to ${opts.results}; next: node selvedge/eval/harness.mjs readme`);
  return 0;
}

async function cmdRun(opts) {
  if (!SETS.includes(opts.set)) throw new UsageError('run needs --set held-out or --set tuning');
  const outside = heldOutDir();
  const cases = checkedCases(opts.repo, opts.set, outside);
  const engine = engineOf();
  const workDir = opts.workDir || join(tmpdir(), 'selvedge-eval-work', `${opts.set}-${engine.selvedge_version}-${new Date().toISOString().replace(/[:.]/g, '')}-${randomBytes(3).toString('hex')}`);
  if (insideRepo(opts.repo, workDir)) throw workDirInvalid(`${workDir} is inside the repository ${opts.repo}; run folders, clones and logs live outside it`);
  const meta = { set: opts.set, engine, planner_repeats: opts.plannerRepeats, runner_repeats: opts.runnerRepeats, case_ids_sha256: caseIdsHash(cases) };
  const metaFile = join(workDir, 'meta.json');
  if (existsSync(metaFile)) {
    const old = readJsonFile(metaFile);
    if (!opts.resume || JSON.stringify(old) !== JSON.stringify(meta)) {
      const why = opts.resume ? ` of another set, engine, repeat count or case list (${JSON.stringify(old)})` : '; pass --resume to finish it, or name a new --work-dir';
      throw workDirInvalid(`${workDir} already holds a run${why}`);
    }
  } else writeAtomic(metaFile, jsonText(meta));
  const groups = groupTargets(cases, opts.set, opts.repo, outside);
  note(`work dir ${workDir}: ${cases.length} case(s) on ${groups.length} target(s), set ${opts.set}, selvedge ${engine.selvedge_version}, planner ${engine.planner_model}`);
  try {
    for (const g of groups) {
      const tdir = join(workDir, 'targets', g.slug);
      const rf = join(tdir, 'result.json');
      if (existsSync(rf) && readJsonFile(rf).status === 'done') {
        note(`${g.key}: done in an earlier pass, kept`);
        continue;
      }
      const started = Date.now();
      const res = await runTarget(g, tdir, opts);
      res.wall_ms = Date.now() - started;
      writeAtomic(rf, jsonText(res));
      note(`${g.key}: done in ${Math.round(res.wall_ms / 1000)} s`);
    }
  } finally {
    runDriver('stop', [join(workDir, 'driver-shared')], join(workDir, 'driver-stop'));
  }
  return appendAndPrint(opts, report(meta, cases, groups, workDir));
}

function cmdScore(opts) {
  if (!opts.workDir) throw new UsageError('score needs --work-dir <dir>');
  const metaFile = join(opts.workDir, 'meta.json');
  if (!existsSync(metaFile)) throw workDirInvalid(`${metaFile} does not exist`);
  const meta = readJsonFile(metaFile);
  if (!SETS.includes(meta.set)) throw workDirInvalid(`${metaFile} names no set`);
  const cases = checkedCases(opts.repo, meta.set, heldOutDir());
  if (meta.case_ids_sha256 !== caseIdsHash(cases)) throw workDirInvalid(`${opts.workDir} ran another case list than the set now holds`);
  return appendAndPrint(opts, report(meta, cases, groupTargets(cases, meta.set, opts.repo, heldOutDir()), opts.workDir));
}

// --- CLI ----------------------------------------------------------------------------------------

function parseArgs(argv) {
  const o = { repo: DEFAULT_REPO, plannerRepeats: 1, runnerRepeats: 1, resume: false, positional: [] };
  const value = (i, flag) => {
    if (i + 1 >= argv.length) throw new UsageError(`${flag} needs a value`);
    return argv[i + 1];
  };
  const count = (v, flag) => {
    if (!/^[1-9][0-9]*$/.test(v)) throw new UsageError(`${flag} takes a whole number >= 1`);
    return Number(v);
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--repo') o.repo = resolve(value(i++, a));
    else if (a === '--set') o.set = value(i++, a);
    else if (a === '--results') o.results = resolve(value(i++, a));
    else if (a === '--readme') o.readme = resolve(value(i++, a));
    else if (a === '--work-dir') o.workDir = resolve(value(i++, a));
    else if (a === '--planner-repeats') o.plannerRepeats = count(value(i++, a), a);
    else if (a === '--runner-repeats') o.runnerRepeats = count(value(i++, a), a);
    else if (a === '--resume') o.resume = true;
    else if (a === '-h' || a === '--help') o.positional.unshift('help');
    else if (a.startsWith('-')) throw new UsageError(`unknown flag ${a}`);
    else o.positional.push(a);
  }
  o.results = o.results || join(o.repo, EVAL_REL, 'results.json');
  o.readme = o.readme || join(o.repo, 'selvedge', 'README.md');
  return o;
}

export async function main(argv) {
  const opts = parseArgs(argv);
  const [cmd, ...rest] = opts.positional;
  if (rest.length) throw new UsageError(`unexpected argument ${rest[0]}`);
  switch (cmd) {
    case undefined:
    case 'help':
      say(USAGE);
      return cmd ? 0 : 2;
    case 'run':
      return cmdRun(opts);
    case 'score':
      return cmdScore(opts);
    case 'readme':
      return cmdReadme(opts);
    case 'check-readme':
      return cmdCheckReadme(opts);
    default:
      throw new UsageError(`unknown command ${cmd}`);
  }
}

if (isMain(import.meta.url)) {
  let code;
  try {
    code = await main(process.argv.slice(2));
  } catch (e) {
    if (e instanceof UsageError) {
      process.stderr.write(`harness: ${e.message}\n\n${USAGE}\n`);
      code = 2;
    } else if (e instanceof Failure) {
      for (const l of e.lines) process.stderr.write(`harness: FAIL ${l}\n`);
      code = 1;
    } else {
      process.stderr.write(`harness: CANNOT RUN — ${e && e.stack ? e.stack : e}\n`);
      code = 2;
    }
  }
  process.exitCode = code;
}
